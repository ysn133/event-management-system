CREATE TABLE IF NOT EXISTS prestataires (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom TEXT NOT NULL CHECK (btrim(nom) <> ''),
  contact TEXT NOT NULL CHECK (btrim(contact) <> ''),
  type_service TEXT NOT NULL CHECK (btrim(type_service) <> ''),
  tarif NUMERIC(12, 2) NOT NULL CHECK (tarif >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS services_prestataire (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prestataire_id BIGINT NOT NULL
    REFERENCES prestataires (id) ON DELETE CASCADE,
  nom TEXT NOT NULL CHECK (btrim(nom) <> ''),
  description TEXT,
  tarif NUMERIC(12, 2) NOT NULL CHECK (tarif >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS services_prestataire_prestataire_id_idx
  ON services_prestataire (prestataire_id);
