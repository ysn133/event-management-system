BEGIN;

CREATE TABLE organisateurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    mot_de_passe_hash VARCHAR(255) NOT NULL,
    CONSTRAINT uk_organisateurs_email UNIQUE (email)
);

CREATE TABLE evenements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organisateur_id BIGINT NOT NULL,
    titre VARCHAR(200) NOT NULL,
    description TEXT,
    date_debut TIMESTAMPTZ NOT NULL,
    date_fin TIMESTAMPTZ NOT NULL,
    lieu VARCHAR(255),
    statut VARCHAR(30) NOT NULL DEFAULT 'PLANIFIE',
    CONSTRAINT fk_evenements_organisateur
        FOREIGN KEY (organisateur_id)
        REFERENCES organisateurs (id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_evenements_periode
        CHECK (date_fin > date_debut)
);

CREATE TABLE prestataires (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(150) NOT NULL,
    contact VARCHAR(255) NOT NULL,
    type_service VARCHAR(100) NOT NULL,
    tarif NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_prestataires_tarif
        CHECK (tarif >= 0)
);

CREATE TABLE services_prestataire (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prestataire_id BIGINT NOT NULL,
    nom VARCHAR(150) NOT NULL,
    description TEXT,
    tarif NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_services_prestataire_prestataire
        FOREIGN KEY (prestataire_id)
        REFERENCES prestataires (id)
        ON DELETE CASCADE,
    CONSTRAINT ck_services_prestataire_tarif
        CHECK (tarif >= 0)
);

CREATE TABLE contrats_prestataire (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prestataire_id BIGINT NOT NULL,
    evenement_id BIGINT NOT NULL,
    prestation VARCHAR(255) NOT NULL,
    montant NUMERIC(19, 2) NOT NULL,
    date_prestation TIMESTAMPTZ NOT NULL,
    statut VARCHAR(50) NOT NULL,
    CONSTRAINT fk_contrats_prestataire_prestataire
        FOREIGN KEY (prestataire_id)
        REFERENCES prestataires (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_contrats_prestataire_evenement
        FOREIGN KEY (evenement_id)
        REFERENCES evenements (id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_contrats_prestataire_montant
        CHECK (montant >= 0)
);

CREATE TABLE salles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(150) NOT NULL,
    capacite INTEGER NOT NULL,
    adresse TEXT NOT NULL,
    prix NUMERIC(19, 2) NOT NULL,
    CONSTRAINT ck_salles_capacite
        CHECK (capacite > 0),
    CONSTRAINT ck_salles_prix
        CHECK (prix > 0)
);

CREATE TABLE reservations_salle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    salle_id BIGINT NOT NULL,
    evenement_id BIGINT NOT NULL,
    date_debut TIMESTAMPTZ NOT NULL,
    date_fin TIMESTAMPTZ NOT NULL,
    prix NUMERIC(19, 2) NOT NULL,
    statut VARCHAR(50) NOT NULL DEFAULT 'EN_ATTENTE',
    CONSTRAINT fk_reservations_salle_salle
        FOREIGN KEY (salle_id)
        REFERENCES salles (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_reservations_salle_evenement
        FOREIGN KEY (evenement_id)
        REFERENCES evenements (id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_reservations_salle_periode
        CHECK (date_fin > date_debut),
    CONSTRAINT ck_reservations_salle_prix
        CHECK (prix >= 0)
);

CREATE TABLE budgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evenement_id BIGINT NOT NULL,
    montant_total NUMERIC(19, 2) NOT NULL,
    statut VARCHAR(20) NOT NULL DEFAULT 'OUVERT',
    CONSTRAINT uk_budgets_evenement_id UNIQUE (evenement_id),
    CONSTRAINT fk_budgets_evenement
        FOREIGN KEY (evenement_id)
        REFERENCES evenements (id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_budgets_montant_total
        CHECK (montant_total > 0),
    CONSTRAINT ck_budgets_statut
        CHECK (statut IN ('OUVERT', 'CLOTURE'))
);

CREATE TABLE depenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    budget_id BIGINT NOT NULL,
    description VARCHAR(255) NOT NULL,
    montant NUMERIC(19, 2) NOT NULL,
    categorie VARCHAR(100) NOT NULL,
    date_depense DATE NOT NULL,
    statut VARCHAR(50) NOT NULL DEFAULT 'PREVUE',
    CONSTRAINT fk_depenses_budget
        FOREIGN KEY (budget_id)
        REFERENCES budgets (id)
        ON DELETE CASCADE,
    CONSTRAINT ck_depenses_montant
        CHECK (montant > 0),
    CONSTRAINT ck_depenses_statut
        CHECK (statut IN ('PREVUE', 'EN_ATTENTE', 'PAYEE', 'ANNULEE'))
);

CREATE TABLE invites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(150) NOT NULL,
    email VARCHAR(255),
    telephone VARCHAR(50),
    CONSTRAINT ck_invites_contact
        CHECK (email IS NOT NULL OR telephone IS NOT NULL)
);

CREATE TABLE invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invite_id BIGINT NOT NULL,
    evenement_id BIGINT NOT NULL,
    date_envoi TIMESTAMPTZ,
    statut VARCHAR(50) NOT NULL DEFAULT 'EN_ATTENTE',
    CONSTRAINT uk_invitations_invite_evenement
        UNIQUE (invite_id, evenement_id),
    CONSTRAINT fk_invitations_invite
        FOREIGN KEY (invite_id)
        REFERENCES invites (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_invitations_evenement
        FOREIGN KEY (evenement_id)
        REFERENCES evenements (id)
        ON DELETE RESTRICT
);

CREATE INDEX idx_evenements_organisateur_id
    ON evenements (organisateur_id);
CREATE INDEX idx_services_prestataire_prestataire_id
    ON services_prestataire (prestataire_id);
CREATE INDEX idx_contrats_prestataire_prestataire_id
    ON contrats_prestataire (prestataire_id);
CREATE INDEX idx_contrats_prestataire_evenement_id
    ON contrats_prestataire (evenement_id);
CREATE INDEX idx_reservations_salle_salle_id
    ON reservations_salle (salle_id);
CREATE INDEX idx_reservations_salle_evenement_id
    ON reservations_salle (evenement_id);
CREATE INDEX idx_depenses_budget_id
    ON depenses (budget_id);
CREATE INDEX idx_invitations_invite_id
    ON invitations (invite_id);
CREATE INDEX idx_invitations_evenement_id
    ON invitations (evenement_id);

CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_prestataires_updated_at
BEFORE UPDATE ON prestataires
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

COMMIT;
